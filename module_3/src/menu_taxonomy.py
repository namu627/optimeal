# -*- coding: utf-8 -*-
"""OptiMeal 모듈3 · 메뉴 분류 체계 (주식 유형 · 국 유형 · 카테고리 재분류)

배경(2026-08-11 영양사 지적 3건):
  1. 주식 슬롯에 '스프'가 단독으로 들어갔다. 스프는 밥·면 없이 주식이 될 수 없다.
  2. 원본 `grouping_type='일품요리'` 171종이 통째로 주식에 매핑돼 있는데, 그 안에
     통삼겹스테이크·가지탕수육·만두처럼 **주찬 성격** 메뉴가 섞여 있다.
  3. 메뉴 궁합이 고려되지 않는다. 국수 + 부대찌개는 성립하지 않는다
     (찌개·전골·탕은 밥과 배식된다).

본 모듈은 **메뉴명 키워드 기반 결정론적 분류기**다. LLM·확률 출력을 쓰지 않는다.

분류 규칙 두 가지 핵심:
  · **접미사 우선(가장 뒤에 오는 키워드가 이긴다)** — 한국어 음식명은 끝에 요리 형태가
    온다. '죽순콩나물밥'은 밥(끝) / '찬밥이용닭죽'은 죽(끝)이 정답이며, 단순 부분일치로는
    둘 다 틀린다.
  · **오탐 토큰 사전 제거** — '죽순'의 죽, '탕수육'의 탕처럼 다른 낱말의 일부인 글자를
    먼저 마스킹한다. 이걸 빼면 탕수육이 탕(국물)으로 분류된다.

기준 문서: FR-11 / PRD §끼니 구성 / 제약조건 정의서 H-4
"""
from __future__ import annotations

import re

# ===========================================================================
# (A) 오탐 토큰 — 다른 낱말의 일부라서 키워드로 세면 안 되는 표기
# ===========================================================================
#   예) '죽순'의 죽은 죽(粥)이 아니다. '탕수육'의 탕은 국물이 아니다.
#   매칭 전에 이 토큰들을 중립 문자로 치환한다.
FALSE_FRIENDS: tuple[str, ...] = (
    "죽순",          # 죽(粥) 아님 — 죽순콩나물밥
    "탕수",          # 탕(국물) 아님 — 탕수육·버섯탕수
    "탕평",          # 탕평채
    "그라탕",        # 탕(국물) 아님 — 오븐 그라탱
    "면역",          # 면(국수) 아님
    "라면월남쌈",    # 라면 사리를 쓴 튀김/쌈 — 면요리 아님(반찬)
    "청국장",        # 국(국물) 아님 — 발효 장류. '청국장찌개'는 찌개로 따로 잡힌다
    "콩국물",        # 국(국물) 아님 — 소스. '콩국수'는 국수로 따로 잡힌다
)
_MASK = "◇"


def _normalize(name: str) -> str:
    """공백 제거 + 오탐 토큰 마스킹. 분류 전 공통 전처리."""
    s = re.sub(r"\s+", "", name or "")
    for token in FALSE_FRIENDS:
        s = s.replace(token, _MASK * len(token))
    return s


def _last_match_kind(text: str, spec: tuple[tuple[str, tuple[str, ...]], ...]) -> str | None:
    """키워드가 **가장 뒤에** 나타나는 유형을 고른다(접미사 우선).

    한국어 음식명은 끝에 요리 형태가 오므로, 여러 유형 키워드가 섞인 이름
    ('찬밥이용닭죽')에서 끝에 가까운 쪽이 실제 요리 형태다.

    Args:
        text: `_normalize` 를 거친 메뉴명.
        spec: ((유형, (키워드, ...)), ...).

    Returns:
        유형명. 어떤 키워드도 없으면 None.
    """
    best_kind, best_pos = None, -1
    for kind, keywords in spec:
        for kw in keywords:
            pos = text.rfind(kw)
            if pos > best_pos:
                best_kind, best_pos = kind, pos
    return best_kind


# ===========================================================================
# (B) 주식 유형 — 탄수화물 주식인가, 아닌가
# ===========================================================================
# 주식 자격이 있는 유형(= 끼니의 탄수화물 base). 영양사 확정(2026-08-11).
STAPLE_KINDS: frozenset[str] = frozenset({"rice", "noodle", "porridge", "bread"})

#   외래어 주식(오므라이스·빠에야·리소토·라자냐 등)이 빠지면 밥·면 요리가 반찬으로
#   분류돼 "주식 없는 끼니"가 다시 생긴다 → 실데이터 전수 검증(2026-08-11)에서 확인된
#   표기를 모두 넣었다. 새 표기가 나오면 여기에 추가한다.
STAPLE_SPEC: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("rice", ("밥", "비빔", "리조또", "리조토", "리소토", "필라프", "누룽지", "떡국",
              "떡만둣국", "약식", "라이스", "빠에야", "파에야", "아란치니", "스시",
              "고랭", "범벅")),
    ("noodle", ("국수", "면", "파스타", "스파게티", "우동", "라면", "냉면", "쫄면",
                "짜장", "짬뽕", "누들", "소바", "포케", "수제비", "뇨끼", "뇨키",
                "푸실리", "팟타야", "팟타이", "라자냐", "라쟈냐", "마카로니", "펜네")),
    ("porridge", ("죽", "미음", "타락", "응이")),
    ("bread", ("샌드위치", "버거", "토스트", "또띠아", "토띠아", "피자", "빵", "브리또",
               "랩", "씨리얼", "시리얼", "뮤즐리")),
    ("soup_only", ("스프", "수프", "포타주", "차우더")),
)


def classify_staple_kind(name: str) -> str:
    """메뉴명에서 주식 유형을 판정한다.

    Args:
        name: 메뉴명(원문).

    Returns:
        'rice' | 'noodle' | 'porridge' | 'bread' | 'soup_only' | 'other'.
        `STAPLE_KINDS` 에 속한 값만 주식 슬롯 자격이 있다.

    Examples:
        >>> classify_staple_kind("죽순콩나물밥")
        'rice'
        >>> classify_staple_kind("찬밥이용닭죽")
        'porridge'
        >>> classify_staple_kind("포니언 스프")
        'soup_only'
    """
    return _last_match_kind(_normalize(name), STAPLE_SPEC) or "other"


def is_staple(name: str) -> bool:
    """주식 슬롯에 단독으로 들어갈 자격이 있는가(탄수화물 주식인가)."""
    return classify_staple_kind(name) in STAPLE_KINDS


# ===========================================================================
# (C) 국 유형 — 밥 전용(국물 주찬)인가, 어디에나 되는 국인가
# ===========================================================================
# 'stew' = 찌개·전골·탕 등 국물 주찬. 영양사 확정: 밥류 주식과만 배식한다.
# 'soup' = 맑은국·미역국·스프 등. 어떤 주식과도 배식 가능.
STEW_KIND = "stew"
SOUP_SPEC: tuple[tuple[str, tuple[str, ...]], ...] = (
    (STEW_KIND, ("찌개", "전골", "탕", "스튜", "샤브", "나베", "지리", "육개장",
                 "굴라쉬", "밀푀유")),
    ("soup", ("국", "스프", "수프", "포타주", "차우더", "장국", "냉국", "옹심이",
              "수제비", "효종갱")),
)


def detect_soup_kind(name: str) -> str | None:
    """국물요리 키워드가 **있을 때만** 유형을 돌려준다. 없으면 None.

    "이 메뉴가 국물요리인가?"를 묻는 자리(카테고리 재분류)에서 쓴다.
    `classify_soup_kind` 의 기본값 'stew' 를 여기에 쓰면 통삼겹스테이크·가지탕수육
    같은 비국물 메뉴가 전부 국으로 분류된다(2026-08-11 전수 검증에서 실제 발생).
    """
    return _last_match_kind(_normalize(name), SOUP_SPEC)


def classify_soup_kind(name: str) -> str:
    """**국 카테고리 메뉴**가 '국물 주찬(stew)'인지 '일반 국(soup)'인지 판정한다.

    Returns:
        'stew' | 'soup'. 키워드가 없으면 보수적으로 'stew'(밥 전용)로 본다 —
        정체불명 국물요리를 면·빵과 붙이는 쪽이 더 위험하기 때문이다.
        ※ 이 기본값은 "이미 국으로 분류된 메뉴" 전제에서만 타당하다.
          국인지 아닌지를 판정하려면 `detect_soup_kind` 를 쓸 것.
    """
    return detect_soup_kind(name) or STEW_KIND


# ===========================================================================
# (D) 궁합 규칙 — (주식 유형 × 국 유형)
# ===========================================================================
def is_compatible(staple_kind: str, soup_kind: str) -> bool:
    """주식 유형과 국 유형이 함께 배식 가능한가.

    영양사 확정 규칙(2026-08-11): **찌개·전골·탕은 밥류 주식과만** 배식한다.
    면·죽·빵 주식에는 맑은국류만 붙인다. (예: 국수 + 부대찌개 ✗)
    """
    if soup_kind != STEW_KIND:
        return True
    return staple_kind == "rice"


# ===========================================================================
# (E) 카테고리 재분류 — grouping_type + 메뉴명 → menu_category
# ===========================================================================
# 원본 grouping_type 의 1:1 매핑(구버전). 일품요리를 통째로 주식에 넣는 게 문제였다.
BASE_CATEGORY_MAP: dict[str, str] = {
    "밥": "주식",
    "일품요리": "주식",
    "국": "국",
    "찌개": "찌개",
    "반찬": "반찬",
    "주찬": "반찬",
    "부찬": "반찬",
    "김치": "반찬",
    "후식": "후식",
    "음료": "음료",
}
DEFAULT_CATEGORY = "기타"


def resolve_menu_category(grouping_type: str, name: str) -> str:
    """grouping_type 과 메뉴명으로 최종 `menu_category` 를 결정한다.

    구 매핑과의 차이(2026-08-11, 영양사 지적 반영):
      · 주식으로 갈 뻔한 메뉴 중 **탄수화물 주식이 아닌 것**을 걸러낸다.
        - 스프류        → '국'   (샌드위치와 함께 낼 수 있는 국물로 쓴다)
        - 탕·전골류     → '국'   (예: 호박잎 삼계탕 — 일품요리로 라벨돼 있으나 탕이다)
        - 그 외(스테이크·탕수육·만두·롤 등) → '반찬' (현장에서 주찬으로 배식)
      · 밥·국·반찬 등 나머지 grouping_type 은 기존 매핑 그대로 둔다.

    Args:
        grouping_type: 원본 xlsx 의 분류값.
        name: 메뉴명.

    Returns:
        `nutrition_recipe.menu_category` 허용값.
    """
    base = BASE_CATEGORY_MAP.get(str(grouping_type or "").strip(), DEFAULT_CATEGORY)
    if base != "주식":
        return base
    if is_staple(name):
        return "주식"
    # 주식 자격 없음 → **국물요리 신호가 실제로 있을 때만** 국, 아니면 반찬.
    #   detect_soup_kind(기본값 없음)를 쓴다. classify_soup_kind 를 쓰면 키워드가
    #   전혀 없는 스테이크·탕수육까지 국으로 간다.
    if classify_staple_kind(name) == "soup_only" or detect_soup_kind(name) is not None:
        return "국"
    return "반찬"
